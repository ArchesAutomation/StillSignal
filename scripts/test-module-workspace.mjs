import assert from "node:assert/strict";
import { chromium } from "playwright";
const origin = process.env.PAGE_LAYOUT_URL || "http://localhost:3113";
const browser = await chromium.launch({ executablePath: process.env.PAGE_LAYOUT_BROWSER || "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
const context = await browser.newContext({ viewport: { width: 1600, height: 1050 } });
const page = await context.newPage(); page.setDefaultTimeout(10000);
const errors = []; page.on("pageerror", e => errors.push(e.message));
try {
  await page.goto(origin + "/review");
  await page.locator('[data-module-id="writing"] textarea').waitFor();
  await page.locator('[data-module-id="moments"] .ss-inline-moment').first().waitFor();
  console.log("Journal modules loaded");
  if (process.env.PAGE_LAYOUT_SCREENSHOTS) await page.screenshot({ path: `${process.env.PAGE_LAYOUT_SCREENSHOTS}/module-default-desktop.png` });
  const writing = page.locator('[data-module-id="writing"]');
  const input = writing.getByLabel("Journal reflection", { exact: true });
  await input.fill("Keep these unsaved words while I build my page");
  const handle = await input.elementHandle();
  await page.getByRole("button", { name: "Customize workspace", exact: true }).first().click();
  await page.getByRole("button", { name: "Add section", exact: true }).first().click();
  const newSection = page.getByLabel("Section name: New section", { exact: true });
  const sectionId = await newSection.evaluate(n => n.closest('[data-module-section]').dataset.moduleSection);
  await newSection.fill("My writing corner");
  await page.getByRole("button", { name: "Edit inside Write a reflection", exact: true }).click();
  await page.getByLabel("Section for Write a reflection", { exact: true }).selectOption(sectionId);
  assert.equal(await input.evaluate((n, old) => n === old, handle), true, "moving preserves the same live form");
  assert.equal(await input.inputValue(), "Keep these unsaved words while I build my page");
  await page.getByLabel("Width for Write a reflection", { exact: true }).selectOption("8");
  assert.equal(await writing.evaluate(n => n.parentElement.closest('[data-module-section]').dataset.moduleSection), sectionId);
  await page.getByRole("button", { name: "Add modules", exact: true }).first().click();
  await page.getByLabel("Add to section", { exact: true }).selectOption(sectionId);
  const library = page.getByRole("region", { name: "Module library", exact: true });
  await library.locator("article").filter({ has: page.getByText("Your stage suggestions", { exact: true }) }).getByRole("button", { name: "Add module", exact: true }).click();
  await page.getByRole("button", { name: "Save layout", exact: true }).first().click();
  console.log("Cross-section move, module library, custom width and draft preservation passed");
  await input.fill("");
  await page.reload(); await page.locator('[data-module-id="stage-labels"]').waitFor();
  assert.equal(await writing.evaluate(n => n.parentElement.closest('[data-module-section]').dataset.moduleSection), sectionId);
  assert.equal(await writing.evaluate(n => n.style.gridColumn), "span 8");
  console.log("Saved module composition survives reload");
  await page.getByRole("button", { name: "Customize workspace", exact: true }).first().click();
  const calendarHandle = page.getByRole("button", { name: "Drag Calendar & previous entries module", exact: true });
  await calendarHandle.scrollIntoViewIfNeeded();
  const source = await calendarHandle.boundingBox();
  const main = await page.locator('[data-module-section="main"]').boundingBox();
  await page.mouse.move(source.x + 20, source.y + 15); await page.mouse.down();
  assert.equal(await page.locator(".ss-module-held").count(), 1);
  await page.mouse.move(main.x + 20, source.y + 15, { steps: 10 }); await page.mouse.up();
  assert.equal(await page.locator('[data-module-id="calendar"]').evaluate(n => n.parentElement.closest('[data-module-section]').dataset.moduleSection), "main");
  if (process.env.PAGE_LAYOUT_SCREENSHOTS) await page.screenshot({ path: `${process.env.PAGE_LAYOUT_SCREENSHOTS}/module-builder-desktop.png` });
  await page.getByRole("button", { name: "Cancel", exact: true }).first().click();
  assert.equal(await page.locator('[data-module-id="calendar"]').evaluate(n => n.parentElement.closest('[data-module-section]').dataset.moduleSection), "side");
  console.log("Pointer drag between big sections, floating state, and cancel passed");
  const other = await context.newPage();
  await other.goto(origin + "/review");
  await other.locator('[data-module-id="stage-labels"]').waitFor();
  await other.locator('[data-module-id="stage-labels"]').getByLabel("Suggestion stage", { exact: true }).selectOption("management");
  await page.locator(".ss-reference-nav").getByRole("button", { name: "Settings", exact: true }).click();
  const dialog = page.locator("dialog.legacy-workspace");
  await dialog.getByLabel("Stage to customize", { exact: true }).selectOption("management");
  await dialog.getByRole("button", { name: "Add label", exact: true }).click();
  await dialog.getByLabel("Management label 7", { exact: true }).fill("Patient with my winner");
  await dialog.getByRole("button", { name: "Save labels", exact: true }).click();
  await dialog.getByText("Management labels saved. Journal suggestions are updated.", { exact: true }).waitFor();
  if (process.env.PAGE_LAYOUT_SCREENSHOTS) await page.screenshot({ path: `${process.env.PAGE_LAYOUT_SCREENSHOTS}/stage-label-settings.png` });
  await dialog.getByRole("button", { name: "Close workspace tools", exact: true }).click();
  await page.locator('[data-module-id="stage-labels"]').getByLabel("Suggestion stage", { exact: true }).selectOption("management");
  await page.locator('[data-module-id="stage-labels"]').getByText("Patient with my winner", { exact: true }).waitFor();
  await other.locator('[data-module-id="stage-labels"]').getByText("Patient with my winner", { exact: true }).waitFor();
  await other.close();
  const options = await page.locator('[data-module-id="moments"] datalist').last().locator('option').allTextContents();
  assert.ok(options.includes("Patient with my winner"), "existing moment suggestions use the saved settings");
  console.log("Settings changes reach stage module, existing entries, and another open window");
  for (const [label, name] of [["Patterns", "Heart-rate analytics"], ["Stillness", "Stillness"], ["Command Center", "Command Center"], ["Daily journal", "Daily journal"]]) {
    await page.locator(".ss-reference-nav").getByRole("button", { name, exact: true }).click();
    const welcome = page.getByRole("button", { name: "I’m here", exact: true });
    if (await welcome.isVisible()) await welcome.click();
    await page.getByRole("button", { name: label === "Command Center" ? "Edit dashboard" : "Customize workspace", exact: true }).first().click();
    await page.locator(label === "Command Center" ? ".cc-drag-handle" : ".ss-module-canvas:not([hidden]) .ss-module-controls").first().waitFor();
    await page.getByRole("button", { name: "Cancel", exact: true }).first().click();
    console.log(label, "editor passed");
  }
  for (const width of [1600, 1024, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, width + "px has no overflow");
    if (process.env.PAGE_LAYOUT_SCREENSHOTS) await page.screenshot({ path: `${process.env.PAGE_LAYOUT_SCREENSHOTS}/module-journal-${width}.png` });
  }
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
